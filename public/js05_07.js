// ボタンにマウスカーソルを重ねたとき、薄いグレーのボタンに変更する
function over() {
    document.getElementById("img").src 
                            = "img/regist_button2.png";
}

// ボタンからマウスカーソルを離したとき、濃いグレーのボタンに変更する
function out() {
    document.getElementById("img").src 
                            = "img/regist_button1.png";
}
